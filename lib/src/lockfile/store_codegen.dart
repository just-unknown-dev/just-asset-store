/// The two files the store generates, so installed items register
/// themselves without anyone editing `main_editor.dart` or the game's boot.
library;

import '../catalog/item_manifest.dart';

/// Writes `store_modules.g.dart` and `store_extensions.g.dart`.
///
/// Both list what installed items declare in their manifests, sorted by
/// each entry's `order` and then the item id, so the output depends only
/// on what is installed. Names come from manifests already checked to be
/// plain Dart names in the item's own libraries: nothing else can reach
/// the generated code.
abstract final class StoreCodegen {
  /// The editor module list for [items].
  static String modules(Iterable<ItemManifest> items) {
    final entries = [
      for (final item in items)
        for (final m in item.modules)
          (item.id, m.order, m.library, m.className),
    ]..sort(_byOrder);
    final aliases = _aliases(entries.map((e) => e.$3));
    final out = StringBuffer()
      ..write(_header)
      ..writeln(
        "import 'package:just_game_engine_editor/just_game_engine_editor.dart'",
      )
      ..writeln('    show EditorModule;');
    for (final a in aliases.entries) {
      out.writeln("import '${a.key}' as ${a.value};");
    }
    out
      ..writeln()
      ..writeln('/// The editor modules of the items installed from the Asset')
      ..writeln('/// Store, in the order they register.');
    if (entries.isEmpty) {
      out.writeln('List<EditorModule> storeModules() => [];');
    } else {
      out.writeln('List<EditorModule> storeModules() => [');
      for (final e in entries) {
        out.writeln('  ${aliases[e.$3]}.${e.$4}(),');
      }
      out.writeln('];');
    }
    return '$out';
  }

  /// The runtime extension list for [items].
  static String extensions(Iterable<ItemManifest> items) {
    final entries = [
      for (final item in items)
        for (final x in item.extensions)
          (item.id, x.order, x.library, x.constant),
    ]..sort(_byOrder);
    final aliases = _aliases(entries.map((e) => e.$3));
    final out = StringBuffer()
      ..write(_header)
      ..writeln("import 'package:just_game_engine/just_game_engine.dart'")
      ..writeln('    show ContextExtension;');
    for (final a in aliases.entries) {
      out.writeln("import '${a.key}' as ${a.value};");
    }
    out
      ..writeln()
      ..writeln('/// What the items installed from the Asset Store teach the')
      ..writeln(
        "/// engine: their components, field types and the rest. Spread",
      )
      ..writeln("/// it into the game's EngineConfig extensions.");
    if (entries.isEmpty) {
      out.writeln('const List<ContextExtension> storeExtensions = [];');
    } else {
      out.writeln('const List<ContextExtension> storeExtensions = [');
      for (final e in entries) {
        out.writeln('  ${aliases[e.$3]}.${e.$4},');
      }
      out.writeln('];');
    }
    return '$out';
  }

  static const String _header =
      '// GENERATED by the Just Asset Store from just_store.lock.json.\n'
      '// Do not edit: install, update or remove items in the Asset Store,\n'
      '// or run `just store generate`.\n'
      '//\n'
      '// ignore_for_file: depend_on_referenced_packages, directives_ordering\n'
      '// ignore_for_file: unused_import\n'
      '\n';

  static int _byOrder(
    (String, int, String, String) a,
    (String, int, String, String) b,
  ) {
    final o = a.$2.compareTo(b.$2);
    if (o != 0) return o;
    final i = a.$1.compareTo(b.$1);
    if (i != 0) return i;
    return a.$4.compareTo(b.$4);
  }

  /// One alias per library, numbered in first-use order.
  static Map<String, String> _aliases(Iterable<String> libraries) {
    final out = <String, String>{};
    for (final lib in libraries) {
      out.putIfAbsent(lib, () => 's${out.length}');
    }
    return out;
  }
}
